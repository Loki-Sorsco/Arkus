// Generates prisma/schema.sql (idempotent CREATE TABLE/INDEX IF NOT EXISTS) from prisma/schema.prisma.
// The launcher applies it with node:sqlite on first run, so users never need the Prisma CLI.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..");
const prismaBin = path.join(root, "node_modules", "prisma", "build", "index.js");
const raw = execFileSync(process.execPath, [prismaBin, "migrate", "diff", "--from-empty", "--to-schema-datamodel", path.join(root, "prisma", "schema.prisma"), "--script"], { encoding: "utf8", env: { ...process.env, DATABASE_URL: "file:./schema-gen.db" } });
const sql = raw
  .replace(/CREATE TABLE "/g, 'CREATE TABLE IF NOT EXISTS "')
  .replace(/CREATE UNIQUE INDEX "/g, 'CREATE UNIQUE INDEX IF NOT EXISTS "')
  .replace(/CREATE INDEX "/g, 'CREATE INDEX IF NOT EXISTS "');
fs.writeFileSync(path.join(root, "prisma", "schema.sql"), `-- generated by scripts/schema-sql.mjs; do not edit\n${sql}`);
console.log(`prisma/schema.sql: ${sql.split("\n").length} lines`);
