"use client";
// Pieces of the data grid: the inline cell editor, the editable "new row" (a <tr> staged above the data),
// the sticky changes bar (count · Apply · Discard · Show SQL), and the left-rail table list.
import { useEffect, useRef, useState, type KeyboardEvent } from "react";
import { useWorkspace } from "@/components/shell/workspace";
import { Icon, Kbd, Spinner } from "@/components/ui";
import { cx, fmtNum } from "@/lib/ui";
import { dbBase, isSecretName, post, type DbColumn, type DbTable } from "./db-shared";
import { insertable, isBoolType, isNumType, previewSql, rawText, same, type PendingInsert, type Staged } from "./db-pending";

export const PencilIcon = ({ size = 13 }: { size?: number }) => (
  <svg width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.8" strokeLinecap="round" strokeLinejoin="round" aria-hidden><path d="M12 20h9M16.5 3.5a2.1 2.1 0 013 3L7 19l-4 1 1-4L16.5 3.5z" /></svg>
);
const monoCol = (c?: DbColumn) => !!c && (c.pk || !!c.references || isNumType(c) || /id$/i.test(c.name));

/** Inline editor for one cell: input (mono for ids / numbers) or a true/false/NULL select for booleans.
 * Enter stages, Esc cancels, Tab / Shift+Tab stage-and-move, blur stages when the value changed. */
export function CellEditor({ value, meta, onSave, onCancel, onTab }: { value: unknown; meta?: DbColumn; onSave: (v: unknown) => void; onCancel: () => void; onTab: (dir: 1 | -1, v: unknown) => void }) {
  const bool = isBoolType(meta) || typeof value === "boolean";
  const nullable = meta?.nullable !== false;
  const [text, setText] = useState(rawText(value));
  const [nul, setNul] = useState(value == null);
  const done = useRef(false);
  const current = (): unknown => (nul ? null : text);
  const finish = (fn: () => void) => { if (done.current) return; done.current = true; fn(); };
  const keys = (e: KeyboardEvent<HTMLElement>) => {
    if (e.key === "Enter") { e.preventDefault(); finish(() => onSave(current())); }
    else if (e.key === "Escape") { e.preventDefault(); finish(onCancel); }
    else if (e.key === "Tab") { e.preventDefault(); finish(() => onTab(e.shiftKey ? -1 : 1, current())); }
  };
  if (bool) {
    return (
      <select autoFocus className="select h-8 text-[12.5px] font-mono w-full rounded-none border-amber" value={nul ? "" : text === "true" || text === "1" ? "true" : "false"} onKeyDown={keys} onBlur={() => finish(() => onSave(current()))}
        onChange={(e) => { const v = e.target.value; if (v === "") setNul(true); else { setNul(false); setText(v); } finish(() => onSave(v === "" ? null : v)); }}>
        {nullable && <option value="">NULL</option>}
        <option value="true">true</option>
        <option value="false">false</option>
      </select>
    );
  }
  return (
    <span className="flex items-center gap-1 h-9 px-1">
      <input autoFocus className={cx("input h-7 text-[12.5px] flex-1 min-w-[140px] border-amber", monoCol(meta) && "font-mono", nul && "italic text-dim")} placeholder={nul ? "NULL" : ""} value={nul ? "" : text}
        onChange={(e) => { setNul(false); setText(e.target.value); }} onKeyDown={keys} onFocus={(e) => e.currentTarget.select()}
        onBlur={() => { if (same(value, current())) finish(onCancel); else finish(() => onSave(current())); }} />
      {nullable && !nul && <button type="button" className="btn-subtle btn-xs" title="Set NULL" onMouseDown={(e) => e.preventDefault()} onClick={() => finish(() => onSave(null))}>NULL</button>}
    </span>
  );
}

/** A staged new row: green tint, one input per insertable column, "auto" on generated keys, lock on secrets.
 * Blank cells are left out of the INSERT so the database applies its defaults. */
export function InsertRow({ ins, columns, colMeta, onChange, onRemove, hasActions }: { ins: PendingInsert; columns: string[]; colMeta: Record<string, DbColumn>; onChange: (col: string, v: string) => void; onRemove: () => void; hasActions: boolean }) {
  const cell = "h-9 border-b border-border/60 whitespace-nowrap";
  return (
    <tr className="bg-green/10 group">
      <td className={cx(cell, "px-3 text-green text-[11px] font-mono select-none")} title="New row (not inserted yet)">+</td>
      {columns.map((c) => {
        const m = colMeta[c];
        if (!m || m.secret || isSecretName(c)) return <td key={c} className={cx(cell, "px-3 text-dim font-mono")} title="Secret column: never written by Arkus"><span className="inline-flex items-center gap-1">{Icon.lock({ size: 11 })} skip</span></td>;
        if (!insertable(m, isSecretName)) return <td key={c} className={cx(cell, "px-3 text-dim italic")} title={`${c} is generated by the database`}>auto</td>;
        const required = m.nullable === false && !m.default;
        const ph = m.default ? `default ${m.default}` : m.nullable !== false ? "NULL" : "required";
        return (
          <td key={c} className={cx(cell, "p-0 min-w-[120px]")}>
            {isBoolType(m) ? (
              <select className={cx("select h-8 text-[12.5px] font-mono w-full rounded-none border-transparent bg-transparent focus:border-green", required && !(ins.values[c] ?? "") && "text-amber")} value={ins.values[c] ?? ""} onChange={(e) => onChange(c, e.target.value)}>
                <option value="">{ph}</option><option value="true">true</option><option value="false">false</option>
              </select>
            ) : (
              <input className={cx("input h-8 text-[12.5px] w-full min-w-[120px] rounded-none border-transparent bg-transparent focus:border-green", monoCol(m) && "font-mono", required && !(ins.values[c] ?? "") && "placeholder:text-amber")} placeholder={ph} value={ins.values[c] ?? ""} onChange={(e) => onChange(c, e.target.value)} title={`${c} ${m.type}${m.nullable !== false ? " · null" : ""}${m.default ? ` · default ${m.default}` : ""}`} />
            )}
          </td>
        );
      })}
      {hasActions && <td className={cx(cell, "px-2 text-right")}><button className="btn-icon btn-xs hover:text-red-soft" title="Remove this new row" aria-label="Remove new row" onClick={onRemove}>{Icon.close({ size: 13 })}</button></td>}
    </tr>
  );
}

/** Sticky bar above the footer while anything is staged. */
export function ChangesBar({ staged, engine, applying, problems, showSql, setShowSql, onApply, onDiscard }: { staged: Staged[]; engine: string | null; applying: boolean; problems: string[]; showSql: boolean; setShowSql: (b: boolean) => void; onApply: () => void; onDiscard: () => void }) {
  const n = staged.length;
  return (
    <div className="flex-none border-t border-amber/50 bg-surface arise dev-only">
      <div className="flex items-center gap-2.5 px-6 h-10 text-[12.5px]">
        <span className="w-2 h-2 rounded-full bg-amber apulse flex-none" />
        <span className="font-semibold">{n} pending change{n === 1 ? "" : "s"}</span>
        {problems.length > 0 ? <span className="text-[12px] text-amber truncate" title={problems.join("\n")}>{problems[0]}{problems.length > 1 ? ` (+${problems.length - 1})` : ""}</span> : <span className="text-[12px] text-dim truncate">Nothing is written until you apply.</span>}
        <div className="flex-1" />
        <button className={cx("btn-subtle btn-xs", showSql && "text-text bg-surface-3")} aria-pressed={showSql} onClick={() => setShowSql(!showSql)}>{showSql ? "Hide SQL" : "Show SQL"}</button>
        <button className="btn-ghost btn-xs" disabled={applying} onClick={onDiscard}>Discard</button>
        <button className="btn-primary btn-xs" disabled={applying || !n || problems.length > 0} onClick={onApply} title={problems.length ? problems.join("\n") : "Apply (Ctrl S)"}>{applying ? <Spinner /> : Icon.check({ size: 12 })} Apply <Kbd>⌃S</Kbd></button>
      </div>
      {showSql && (
        <pre className="max-h-[180px] overflow-auto border-t border-border bg-bg-deep px-6 py-2 font-mono text-[12px] leading-[1.7] text-text-2 whitespace-pre">
          {staged.map((s, i) => <div key={i}><span className="text-dim select-none">{String(i + 1).padStart(2, " ")}  </span>{previewSql(s.mutation, engine)}</div>)}
        </pre>
      )}
    </div>
  );
}

/** Left-rail list of tables: name (mono) and a dim row estimate when one is known (> 0); clicking it fetches the exact count. */
export function TablesRail({ tables, current, onPick, q, canCount }: { tables: DbTable[]; current: string | null; onPick: (name: string) => void; q: string; canCount: boolean }) {
  const { project, env } = useWorkspace();
  const [exact, setExact] = useState<Record<string, number | "loading">>({});
  useEffect(() => { setExact({}); }, [env, project.slug]);
  const list = tables.filter((t) => t.name.toLowerCase().includes(q.toLowerCase()));
  const count = async (name: string) => {
    if (!canCount || exact[name] === "loading") return;
    setExact((m) => ({ ...m, [name]: "loading" }));
    const r = await post<{ count?: number; error?: string }>(`${dbBase(project.slug)}/count`, { env, table: name });
    setExact((m) => { const n = { ...m }; if (typeof r.count === "number") n[name] = r.count; else delete n[name]; return n; });
  };
  return (
    <div className="flex-1 overflow-auto py-1.5">
      {list.map((t) => {
        const ex = exact[t.name];
        const est = t.rowEstimate != null && t.rowEstimate > 0 ? t.rowEstimate : null;
        return (
          <div key={t.name} onClick={() => onPick(t.name)} className={cx("list-row group", current === t.name && "active")} title={`${t.name} · ${t.columns.length} columns`}>
            <span className="font-mono text-[12.5px] truncate">{t.name}</span>
            <span className="ml-auto flex-none">
              {ex === "loading" ? <Spinner /> : typeof ex === "number"
                ? <span className="text-[11.5px] text-text-2 tabular-nums">{fmtNum(ex)}</span>
                : canCount
                  ? <button className={cx("text-[11.5px] text-dim tabular-nums hover:text-text cursor-pointer", !est && "opacity-0 group-hover:opacity-100")} title={est ? "Estimated rows. Click for an exact count." : "Click for an exact count."} onClick={(e) => { e.stopPropagation(); count(t.name); }}>{est ? `~${fmtNum(est)}` : "count"}</button>
                  : est ? <span className="text-[11.5px] text-dim tabular-nums" title="Estimated rows">~{fmtNum(est)}</span> : null}
            </span>
          </div>
        );
      })}
      {!list.length && <div className="px-4 py-3 text-[12.5px] text-dim">{tables.length ? "No table matches." : "No tables yet."}</div>}
    </div>
  );
}
