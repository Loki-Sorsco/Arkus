import type { Blueprint, Entity, Column, Endpoint } from "./schema";
import { endpointRef } from "./schema";

export const camel = (s: string) => s.replace(/_([a-z0-9])/g, (_, c: string) => c.toUpperCase());
export const pascal = (s: string) => { const c = camel(s); return c.charAt(0).toUpperCase() + c.slice(1); };
export const modelName = (e: Entity) => pascal(e.name.replace(/\s+/g, "_"));

/** "/api/orders/:id" → "src/app/api/orders/[id]/route.ts" */
export const routeFileFor = (path: string) => `src/app${path.replace(/:([a-zA-Z0-9_]+)\*?/g, "[$1]")}/route.ts`;
/** "/orders/:id" → "src/app/orders/[id]/page.tsx" ("/" → "src/app/page.tsx") */
export const pageFileFor = (path: string) => `src/app${path === "/" ? "" : path.replace(/:([a-zA-Z0-9_]+)\*?/g, "[$1]")}/page.tsx`;

/** Tables sorted so every FK target comes first (cycles broken, appended last). */
export function topoEntities(bp: Blueprint): Entity[] {
  const byTable = new Map(bp.entities.map((e) => [e.table, e]));
  const out: Entity[] = []; const done = new Set<string>(); const visiting = new Set<string>();
  const visit = (e: Entity) => {
    if (done.has(e.table) || visiting.has(e.table)) return;
    visiting.add(e.table);
    for (const c of e.columns) { const t = c.references && byTable.get(c.references.table); if (t && t !== e) visit(t); }
    visiting.delete(e.table); done.add(e.table); out.push(e);
  };
  bp.entities.forEach(visit);
  return out;
}

// ---------------- Prisma ----------------

const PRISMA_TYPES: Record<Column["type"], string> = { text: "String", integer: "Int", numeric: "Decimal", boolean: "Boolean", timestamptz: "DateTime", uuid: "String", jsonb: "Json", date: "DateTime" };

function prismaDefault(c: Column, provider: string): string {
  const d = c.default?.trim();
  if (!d) return "";
  if (/gen_random_uuid|uuid/i.test(d)) return " @default(uuid())";
  if (/^now\(\)|current_timestamp/i.test(d)) return " @default(now())";
  if (/^'.*'$/.test(d)) return ` @default(${JSON.stringify(d.slice(1, -1))})`;
  if (/^(true|false)$/i.test(d)) return ` @default(${d.toLowerCase()})`;
  if (/^-?\d+(\.\d+)?$/.test(d)) return ` @default(${d})`;
  if (c.type === "jsonb" && provider !== "sqlite") return ` @default("${d.replace(/"/g, '\\"')}")`;
  return "";
}

export function toPrismaSchema(bp: Blueprint, provider: "sqlite" | "postgresql" | "mysql" = "sqlite"): string {
  const byTable = new Map(bp.entities.map((e) => [e.table, e]));
  const back = new Map<string, string[]>(); // target table → back-relation lines
  const lines: string[] = [
    "// Generated by Arkus Architect from the blueprint. Edit freely; Arkus re-indexes on change.",
    "generator client {\n  provider = \"prisma-client-js\"\n}", "",
    `datasource db {\n  provider = "${provider}"\n  url      = env("DATABASE_URL")\n}`, "",
  ];
  const relName = (child: string, col: string) => `${child}_${col}`;
  const models: { table: string; head: string; body: string[]; ix: string[] }[] = [];
  for (const e of topoEntities(bp)) {
    const body: string[] = [];
    const fkCountByTarget = new Map<string, number>();
    for (const c of e.columns) if (c.references) fkCountByTarget.set(c.references.table, (fkCountByTarget.get(c.references.table) ?? 0) + 1);
    for (const c of e.columns) {
      const f = camel(c.name);
      let t = c.type === "jsonb" && provider === "sqlite" ? "String" : PRISMA_TYPES[c.type];
      if (c.nullable) t += "?";
      const attrs = [c.pk ? " @id" : "", c.unique && !c.pk ? " @unique" : "", prismaDefault(c, provider), f !== c.name ? ` @map("${c.name}")` : "",
        c.type === "uuid" && provider === "postgresql" ? " @db.Uuid" : "", c.type === "date" && provider === "postgresql" ? " @db.Date" : "", c.type === "timestamptz" && provider === "postgresql" ? " @db.Timestamptz(6)" : ""].join("");
      body.push(`  ${f.padEnd(16)} ${t.padEnd(10)}${attrs}`);
      if (c.references && byTable.has(c.references.table)) {
        const target = byTable.get(c.references.table)!;
        const rel = (fkCountByTarget.get(c.references.table) ?? 0) > 1 || e.table === target.table ? `"${relName(e.table, c.name)}", ` : "";
        const field = camel(c.name.replace(/_id$/, "")) || `${camel(target.table)}Ref`;
        const fieldName = e.columns.some((x) => camel(x.name) === field) ? field + "Rel" : field;
        body.push(`  ${fieldName.padEnd(16)} ${(modelName(target) + (c.nullable ? "?" : "")).padEnd(10)} @relation(${rel}fields: [${f}], references: [${camel(c.references.column)}], onDelete: ${c.nullable ? "SetNull" : "Cascade"})`);
        const backField = rel ? `${camel(e.table)}As${pascal(c.name.replace(/_id$/, ""))}` : camel(e.table);
        const arr = back.get(target.table) ?? []; arr.push(`  ${backField.padEnd(16)} ${modelName(e)}[]${rel ? ` @relation(${rel.replace(/, $/, "")})` : ""}`); back.set(target.table, arr);
      }
    }
    const covered = (i: { columns: string[] }) => i.columns.length === 1 && e.columns.some((c) => c.name === i.columns[0] && (c.pk || c.unique));
    const ix = (e.indexes ?? []).filter((i) => !covered(i)).map((i) => `  @@${i.unique ? "unique" : "index"}([${i.columns.map(camel).join(", ")}])`);
    models.push({ table: e.table, head: `model ${modelName(e)} {`, body, ix });
  }
  for (const m of models) {
    lines.push(m.head, ...m.body, ...(back.get(m.table) ?? []), ...m.ix, `  @@map("${m.table}")`, "}", "");
  }
  return lines.join("\n");
}

// ---------------- SQL DDL ----------------

const PG: Record<Column["type"], string> = { text: "text", integer: "integer", numeric: "numeric(12,2)", boolean: "boolean", timestamptz: "timestamptz", uuid: "uuid", jsonb: "jsonb", date: "date" };
const LITE: Record<Column["type"], string> = { text: "TEXT", integer: "INTEGER", numeric: "REAL", boolean: "INTEGER", timestamptz: "TEXT", uuid: "TEXT", jsonb: "TEXT", date: "TEXT" };

function sqlDefault(c: Column, engine: "postgres" | "sqlite"): string {
  const d = c.default?.trim(); if (!d) return "";
  if (/gen_random_uuid|uuid/i.test(d)) return engine === "postgres" ? " DEFAULT gen_random_uuid()" : " DEFAULT (lower(hex(randomblob(16))))";
  if (/^now\(\)|current_timestamp/i.test(d)) return engine === "postgres" ? " DEFAULT now()" : " DEFAULT CURRENT_TIMESTAMP";
  if (/^(true|false)$/i.test(d)) return engine === "postgres" ? ` DEFAULT ${d.toLowerCase()}` : ` DEFAULT ${d.toLowerCase() === "true" ? 1 : 0}`;
  if (/^'.*'$/.test(d) || /^-?\d+(\.\d+)?$/.test(d)) return ` DEFAULT ${d}`;
  return "";
}

export function toSqlDdl(bp: Blueprint, engine: "postgres" | "sqlite" = "postgres"): string {
  const T = engine === "postgres" ? PG : LITE;
  const q = (s: string) => `"${s}"`;
  const out: string[] = [`-- ${bp.name} · generated by Arkus Architect · ${engine}`, engine === "sqlite" ? "PRAGMA foreign_keys = ON;" : "", ""];
  for (const e of topoEntities(bp)) {
    const cols = e.columns.map((c) => {
      const parts = [`  ${q(c.name)} ${T[c.type]}`, c.pk ? " PRIMARY KEY" : "", c.nullable || c.pk ? "" : " NOT NULL", c.unique && !c.pk ? " UNIQUE" : "", sqlDefault(c, engine)];
      if (c.references) parts.push(` REFERENCES ${q(c.references.table)}(${q(c.references.column)})${c.nullable ? " ON DELETE SET NULL" : " ON DELETE CASCADE"}`);
      return parts.join("");
    });
    out.push(`-- ${e.name}: ${e.description}`.trimEnd(), `CREATE TABLE ${q(e.table)} (`, cols.join(",\n"), ");");
    for (const ix of (e.indexes ?? []).filter((i) => !(i.columns.length === 1 && e.columns.some((c) => c.name === i.columns[0] && (c.pk || c.unique))))) out.push(`CREATE ${ix.unique ? "UNIQUE " : ""}INDEX ${q(`${e.table}_${ix.columns.join("_")}_idx`)} ON ${q(e.table)} (${ix.columns.map(q).join(", ")});`);
    out.push("");
  }
  return out.join("\n");
}

// ---------------- OpenAPI 3.1 ----------------

const oaType = (t: string): Record<string, unknown> => {
  const s = t.toLowerCase();
  if (/number|numeric|integer|int|float/.test(s)) return { type: "number" };
  if (/bool/.test(s)) return { type: "boolean" };
  if (/array|\[\]/.test(s)) return { type: "array", items: {} };
  if (/object|json/.test(s)) return { type: "object" };
  if (/date|time/.test(s)) return { type: "string", format: "date-time" };
  return { type: "string" };
};
const colSchema = (c: Column): Record<string, unknown> => ({ text: { type: "string" }, integer: { type: "integer" }, numeric: { type: "number" }, boolean: { type: "boolean" }, timestamptz: { type: "string", format: "date-time" }, uuid: { type: "string", format: "uuid" }, jsonb: { type: "object" }, date: { type: "string", format: "date" } }[c.type]);

export function toOpenApi(bp: Blueprint): Record<string, unknown> {
  const paths: Record<string, Record<string, unknown>> = {};
  for (const ep of bp.endpoints) {
    const oaPath = ep.path.replace(/:([a-zA-Z0-9_]+)\*?/g, "{$1}");
    const params = [...ep.path.matchAll(/:([a-zA-Z0-9_]+)/g)].map((m) => ({ name: m[1], in: "path", required: true, schema: { type: "string" } }));
    const hasBody = ep.method !== "GET" && ep.method !== "DELETE" && ep.request.length > 0;
    const op: Record<string, unknown> = {
      operationId: camel(ep.name.replace(/[^a-zA-Z0-9]+/g, "_")), summary: ep.name, description: ep.description || undefined,
      tags: [...new Set([...ep.writes, ...ep.reads])].slice(0, 1),
      parameters: [...params, ...(!hasBody ? ep.request.map((r) => ({ name: r.key, in: "query", required: r.required, schema: oaType(r.type) })) : [])],
      ...(hasBody ? { requestBody: { required: true, content: { "application/json": { schema: { type: "object", required: ep.request.filter((r) => r.required).map((r) => r.key), properties: Object.fromEntries(ep.request.map((r) => [r.key, { ...oaType(r.type), description: r.validation }])) } } } } } : {}),
      responses: {
        [ep.method === "POST" ? "201" : "200"]: { description: "OK", content: { "application/json": { schema: { type: "object", properties: Object.fromEntries(ep.response.map((r) => [r.key, oaType(r.type)])) } } } },
        "400": { description: "Validation error" }, ...(ep.auth ? { "401": { description: "Unauthenticated" } } : {}), ...(params.length ? { "404": { description: "Not found" } } : {}),
      },
      security: ep.auth ? [{ cookieAuth: [] }] : [],
      "x-arkus": { reads: ep.reads, writes: ep.writes, internal: !!ep.internal },
    };
    paths[oaPath] = { ...(paths[oaPath] ?? {}), [ep.method.toLowerCase()]: op };
  }
  return {
    openapi: "3.1.0", info: { title: bp.name, version: "0.1.0", description: bp.summary },
    paths,
    components: {
      securitySchemes: { cookieAuth: { type: "apiKey", in: "cookie", name: "session" } },
      schemas: Object.fromEntries(bp.entities.map((e) => [modelName(e), { type: "object", description: e.description, required: e.columns.filter((c) => !c.nullable).map((c) => c.name), properties: Object.fromEntries(e.columns.map((c) => [c.name, colSchema(c)])) }])),
    },
  };
}

// ---------------- tasks.md ----------------

export function toTasksMarkdown(bp: Blueprint): string {
  const L: string[] = [`# ${bp.name} — build plan`, "", bp.summary, "", `**Stack:** ${bp.stack.frontend} · ${bp.stack.backend} · ${bp.stack.database} · auth: ${bp.stack.auth}${bp.stack.payments ? ` · payments: ${bp.stack.payments}` : ""} · ${bp.stack.hosting}`, ""];
  L.push("## Phase 0 — Setup", "- [ ] `npm install` · copy `.env.example` → `.env`", "- [ ] `npx prisma db push` (creates the dev database)", "- [ ] `npm run dev` and open http://localhost:3000", "");
  L.push("## Phase 1 — Database (`prisma/schema.prisma`)");
  for (const e of topoEntities(bp)) L.push(`- [ ] model \`${modelName(e)}\` → table \`${e.table}\` (${e.columns.length} columns${e.indexes?.length ? `, ${e.indexes.length} indexes` : ""})${e.columns.filter((c) => c.references).map((c) => ` · FK ${c.name}→${c.references!.table}`).join("")}`);
  L.push("- [ ] run `npx prisma migrate dev --name init`", "");
  L.push("## Phase 2 — API routes");
  for (const ep of bp.endpoints) L.push(`- [ ] \`${endpointRef(ep)}\` ${ep.name} → \`${routeFileFor(ep.path)}\`${ep.auth ? " · requires session" : ""}${ep.request.length ? ` · validate: ${ep.request.map((r) => r.key).join(", ")}` : ""}${ep.writes.length ? ` · writes ${ep.writes.join(", ")}` : ""}${ep.reads.length ? ` · reads ${ep.reads.join(", ")}` : ""}`);
  L.push("");
  L.push("## Phase 3 — Pages");
  for (const p of bp.pages) L.push(`- [ ] \`${p.path}\` ${p.name} (${p.kind}) → \`${pageFileFor(p.path)}\`${p.fields.length ? ` · fields: ${p.fields.map((f) => f.key).join(", ")}` : ""}${p.calls.length ? ` · calls ${p.calls.join(", ")}` : ""}`);
  L.push("");
  if (bp.services.length || bp.jobs?.length) {
    L.push("## Phase 4 — Services & jobs");
    for (const s of bp.services) L.push(`- [ ] integrate **${s.name}** — ${s.purpose} → \`src/lib/${s.name.toLowerCase().replace(/[^a-z0-9]+/g, "-")}.ts\``);
    for (const jb of bp.jobs ?? []) L.push(`- [ ] job **${jb.name}** (${jb.schedule}) — ${jb.purpose} → \`src/jobs/${jb.name}.ts\``);
    L.push("");
  }
  if (bp.assumptions.length) { L.push("## Assumptions to confirm"); for (const a of bp.assumptions) L.push(`- [${a.chosen ? "x" : " "}] **${a.id}**: ${a.text}${a.alternative ? ` _(alternative: ${a.alternative})_` : ""}`); L.push(""); }
  if (bp.checks.length) { L.push("## Design checks"); for (const c of bp.checks) L.push(`- ${c.ok ? "✅" : "⚠️"} **${c.name}** — ${c.detail}`); L.push(""); }
  return L.join("\n");
}

export function toSpecJson(bp: Blueprint): Record<string, unknown> {
  return {
    arkus: { kind: "blueprint", schema: 1, exportedAt: new Date().toISOString() },
    ...bp,
    layout: { routes: bp.endpoints.map((e) => ({ endpoint: endpointRef(e), file: routeFileFor(e.path) })), pages: bp.pages.map((p) => ({ path: p.path, file: pageFileFor(p.path) })) },
  };
}

export const endpointFileMap = (eps: Endpoint[]) => eps.map((e) => [endpointRef(e), routeFileFor(e.path)] as const);
